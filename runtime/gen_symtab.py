#!/usr/bin/env python3
"""Undermountain Enhanced - write symtab.c: the program's symbols that the
recompiled game may refer to (every "extern NAME" in recomp/x64/*.inc), for
the loader of the self-building version (coffload.c).
Usage: gen_symtab.py RECOMP_X64_DIR OUT.c"""
import re, sys, glob, os
names = set()
for f in sorted(glob.glob(os.path.join(sys.argv[1], '*.inc'))):
    for line in open(f, encoding='latin-1'):
        m = re.match(r'\s*extern\s+([A-Za-z_][A-Za-z0-9_]*)', line)
        if m: names.add(m.group(1))
names = sorted(names)
with open(sys.argv[2], 'w') as o:
    o.write('/* generated by gen_symtab.py - do not edit */\n#include <stddef.h>\n')
    for n in names: o.write('extern char %s[];\n' % n)
    o.write('struct symtab_entry { const char *name; void *addr; };\nconst struct symtab_entry dtu_symtab[] = {\n')
    for n in names: o.write('    { "%s", %s },\n' % (n, n))
    o.write('    { NULL, NULL }\n};\n')
print('%d symbols' % len(names))
